    $ts = strtotime($date);
    $dow = (int)date('N', $ts);
    return date('Y-m-d', strtotime($date . ' -' . ($dow - 1) . ' days'));
}

function fmt_time($t) {
    return $t ? substr((string)$t, 0, 5) : '';
}

function time_to_minutes($t) {
    $t = fmt_time($t);
    if ($t === '' || !preg_match('/^\d{2}:\d{2}$/', $t)) return null;
    return (int)substr($t, 0, 2) * 60 + (int)substr($t, 3, 2);
}

function minutes_phrase($minutes, $lang = 'ru') {
    $n = (int)$minutes;
    if ($n < 0) $n = 0;
    if ($lang === 'by') {
        $forms = ['хвіліна', 'хвіліны', 'хвілін'];
    } else {
        $forms = ['минута', 'минуты', 'минут'];
    }
    $mod10 = $n % 10;
    $mod100 = $n % 100;
    if ($mod10 === 1 && $mod100 !== 11) return $n . ' ' . $forms[0];
    if ($mod10 >= 2 && $mod10 <= 4 && ($mod100 < 12 || $mod100 > 14)) return $n . ' ' . $forms[1];
    return $n . ' ' . $forms[2];
}

function lesson_parts($lesson) {
    $start = time_to_minutes($lesson['time_start'] ?? '');
    $end = time_to_minutes($lesson['time_end'] ?? '');
    $bs = time_to_minutes($lesson['break_start'] ?? '');
    $be = time_to_minutes($lesson['break_end'] ?? '');
    $two = ($bs !== null && $be !== null && $be > $bs && $end !== null && $bs > $start && $be < $end);
    return [
        'start' => $start,
        'end' => $end,
        'break_start' => $bs,
        'break_end' => $be,
        'two_parts' => $two,
    ];
}

function time_value($v) {
    $v = trim((string)$v);
    return preg_match('/^\d{1,2}:\d{2}$/', $v) ? $v : '';
}

function text_value($v) {
    return trim(strip_tags((string)$v));
}

function safe_link($url) {
    $url = trim((string)$url);
    if ($url === '') return '';
    if (!preg_match('#^(https?:)?//#i', $url)) return '';
    return $url;
}